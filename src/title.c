static size_t
str_max_line_len (const char *s)
{
  size_t num_ch, max;
  char c;
  num_ch = max = 0;
  while ((c = *s++)) {
    if (c == '\n') {
      num_ch = 0;
      continue;
    }
    if (++num_ch > max)
      max = num_ch;
  }
  return max;
}

/* sets the title and attribution, returns -1 if failed, 0 if successful */
int
get_titlecard (const char **title, const char **attr)
{
  ASSERT (CLEN (title_fonts) == CLEN (attributions));

  // Get dimensions of outputting terminal
  struct winsize w = {0};
  if (0 > ioctl (STDOUT_FILENO, TIOCGWINSZ, &w))
    return -1;

  // Copy only the titles that would fit in the terminal
  const char *cands[CLEN (title_fonts)];
  const char *cands_attrs[CLEN (attributions)];
  int len = 0;
  for (size_t i = 0; i < CLEN (title_fonts); ++i) {
    if (str_max_line_len (title_fonts[i]) > w.ws_col)
      continue;
    cands[len] = title_fonts[i];
    cands_attrs[len] = attributions[i];
    len++;
  }

  if (len == 0 || !title || !attr)
    return -1;

  srand (time (NULL));
  int r = rand () % len;
  *title = cands[r];
  *attr = cands_attrs[r];

  return 0;
}
